const STORAGE_KEY = 'canai.lang';
const SUPPORTED = ['en', 'ja'];

function detect() {
  // ?lang=en / ?lang=ja が最優先（README や共有リンクから言語を指定できる）
  const q = new URLSearchParams(globalThis.location?.search ?? '').get('lang');
  if (SUPPORTED.includes(q)) return q;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED.includes(saved)) return saved;
  } catch { /* private mode etc. — fall through to browser language */ }
  const nav = (globalThis.navigator?.language ?? 'en').toLowerCase();
  return nav.startsWith('ja') ? 'ja' : 'en';
}

let lang = detect();
const listeners = new Set();

export function getLang() {
  return lang;
}

export function setLang(next) {
  if (!SUPPORTED.includes(next) || next === lang) return;
  lang = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* non-fatal */ }
  for (const fn of listeners) fn(lang);
}

export function onLangChange(fn) {
  listeners.add(fn);
}

