// 単一の理由オブジェクトを、指定ロケール（既定は現在のロケール）の文へ。
export function formatReason(reason, forced) {
  if (typeof reason === 'string') return reason; // 後方互換
  const fn = REASON_TEXT[reason?.code];
  if (!fn) return reason?.code ?? String(reason);
  const l = forced ?? lang;
  const zone = reason.zoneId ? zoneName(reason.zoneId, l) : '';
  return fn(reason, zone)[l === 'ja' ? 1 : 0];
}

export function formatReasons(reasons, forced) {
  return (reasons ?? []).map((r) => formatReason(r, forced)).join(' / ');
}

// runtime-monitor など、UIロケールに依存させたくない層（監査ログ）向けの英語固定版。
export const formatReasonsEn = (reasons) => formatReasons(reasons, 'en');

function zoneName(zoneId, l) {
  const z = ZONE_LABELS[zoneId];
  if (!z) return zoneId;
  return l === 'ja' ? z[1] : z[0];
}

