export function t(key, params) {
  const entry = UI[key];
  if (!entry) return key;
  let s = entry[lang === 'ja' ? 1 : 0];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`%${k}`, v);
  return s;
}

